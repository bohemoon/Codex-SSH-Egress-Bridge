#!/usr/bin/env bash
# codex-ssh-eg-managed
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: install.sh [--wrap-codex]

Environment overrides:
  CODEX_BIN       Existing Codex executable to wrap
  SOCKS_HOST      SOCKS5 listener host (default: 127.0.0.1)
  SOCKS_PORT      SOCKS5 listener port (default: 10809)
  HTTP_PROXY_HOST HTTP adapter host (default: 127.0.0.1)
  HTTP_PROXY_PORT HTTP adapter port (default: 17898)
EOF
}

wrap_codex=0
while [ "$#" -gt 0 ]; do
  case "$1" in
    --wrap-codex) wrap_codex=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

SOCKS_HOST="${SOCKS_HOST:-127.0.0.1}"
SOCKS_PORT="${SOCKS_PORT:-10809}"
HTTP_PROXY_HOST="${HTTP_PROXY_HOST:-127.0.0.1}"
HTTP_PROXY_PORT="${HTTP_PROXY_PORT:-17898}"

for value in "$SOCKS_PORT" "$HTTP_PROXY_PORT"; do
  case "$value" in
    ''|*[!0-9]*) echo "Ports must be integers." >&2; exit 2 ;;
  esac
  if [ "$value" -lt 1 ] || [ "$value" -gt 65535 ]; then
    echo "Port out of range: $value" >&2
    exit 2
  fi
done

project_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/codex-ssh-eg"
data_dir="${XDG_DATA_HOME:-$HOME/.local/share}/codex-ssh-eg"
state_dir="${XDG_STATE_HOME:-$HOME/.local/state}/codex-ssh-eg"
bin_dir="$HOME/.local/bin"
config_file="$config_dir/config"

python_bin="$(command -v python3 || true)"
[ -n "$python_bin" ] || { echo "python3 is required." >&2; exit 1; }

managed_launcher="$bin_dir/codex-ssh-eg"
codex_bin="${CODEX_BIN:-}"
if [ -z "$codex_bin" ]; then
  current_codex="$(command -v codex || true)"
  if [ "$current_codex" = "$bin_dir/codex" ] &&
      grep -Fq 'codex-ssh-eg-managed' "$current_codex" 2>/dev/null &&
      [ -r "$config_file" ]; then
    # shellcheck disable=SC1090
    . "$config_file"
    codex_bin="${CODEX_REAL_BIN:-}"
  else
    codex_bin="$current_codex"
  fi
fi
[ -n "$codex_bin" ] || {
  echo "Codex was not found. Install it first or set CODEX_BIN." >&2
  exit 1
}
codex_bin="$(readlink -f "$codex_bin")"
[ -x "$codex_bin" ] || { echo "Codex executable is not runnable." >&2; exit 1; }
case "$codex_bin" in
  "$managed_launcher"|"$bin_dir/codex")
    echo "Refusing a launcher path that could recurse: $codex_bin" >&2
    exit 1
    ;;
esac

mkdir -p "$config_dir" "$data_dir" "$state_dir" "$bin_dir"
rm -rf "$data_dir/codex_ssh_eg"
cp -R "$project_root/src/codex_ssh_eg" "$data_dir/codex_ssh_eg"
find "$data_dir/codex_ssh_eg" -type d -name __pycache__ -prune -exec rm -rf {} +

{
  echo '# Generated by codex-ssh-eg; contains local paths and must not be shared.'
  printf 'CODEX_REAL_BIN=%q\n' "$codex_bin"
  printf 'PYTHON_BIN=%q\n' "$python_bin"
  printf 'CODEX_SSH_EG_DATA_DIR=%q\n' "$data_dir"
  printf 'CODEX_SSH_EG_STATE_DIR=%q\n' "$state_dir"
  printf 'SOCKS_HOST=%q\n' "$SOCKS_HOST"
  printf 'SOCKS_PORT=%q\n' "$SOCKS_PORT"
  printf 'HTTP_PROXY_HOST=%q\n' "$HTTP_PROXY_HOST"
  printf 'HTTP_PROXY_PORT=%q\n' "$HTTP_PROXY_PORT"
} >"$config_file"
chmod 600 "$config_file"

for name in codex-ssh-eg codex-ssh-eg-ensure-proxy codex-ssh-eg-verify \
  codex-ssh-eg-diagnose codex-ssh-eg-recover-orphan; do
  install -m 755 "$project_root/scripts/linux/bin/$name" "$bin_dir/$name"
done

if [ "$wrap_codex" -eq 1 ]; then
  if [ -e "$bin_dir/codex" ] || [ -L "$bin_dir/codex" ]; then
    if ! grep -Fq 'codex-ssh-eg-managed' "$bin_dir/codex" 2>/dev/null; then
      echo "Refusing to overwrite unmanaged $bin_dir/codex" >&2
      echo "Review and rename it yourself, then rerun with --wrap-codex." >&2
      exit 1
    fi
    rm "$bin_dir/codex"
  fi
  ln -s codex-ssh-eg "$bin_dir/codex"
  echo "Installed managed $bin_dir/codex symlink."
fi

echo "Installed Codex SSH Egress Bridge in $bin_dir"
echo "Run: $bin_dir/codex-ssh-eg-verify"
if [[ ":$PATH:" != *":$bin_dir:"* ]]; then
  echo "Note: add $bin_dir to PATH for command-name discovery."
fi
